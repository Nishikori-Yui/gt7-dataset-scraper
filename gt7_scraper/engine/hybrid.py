from pathlib import Path
from typing import Optional

from ..scraper import run_scraper


def run_hybrid_scraper(
    locale: str,
    db_path: Path,
    image_dir: Path,
    limit: int,
    resume: bool,
    use_playwright: bool,
    rate: float,
    timeout: int,
    workers: int,
    base_locale: str = "gb",
    playwright_workers: int = 0,
    car_list_path: Optional[Path] = None,
    download_images: bool = True,
    show_progress: bool = True,
    progress_callback=None,
    progress_desc: str = "Cars",
    progress_position: int = 0,
    commit_batch: int = 50,
    sqlite_wal: bool = True,
    engines_dir: Optional[Path] = None,
    download_workers: int = 32,
    download_timeout: int = 30,
    download_retries: int = 2,
    catalog_engine: str = "go",
    playwright_engine: str = "node",
    spec_engine: str = "rust",
) -> int:
    return run_scraper(
        locale=locale,
        db_path=db_path,
        image_dir=image_dir,
        limit=limit,
        resume=resume,
        use_playwright=use_playwright,
        rate=rate,
        timeout=timeout,
        workers=workers,
        base_locale=base_locale,
        playwright_workers=playwright_workers,
        car_list_path=car_list_path,
        download_images=download_images,
        show_progress=show_progress,
        progress_callback=progress_callback,
        progress_desc=progress_desc,
        progress_position=progress_position,
        commit_batch=max(1, int(commit_batch or 1)),
        sqlite_wal=sqlite_wal,
        engines_dir=engines_dir,
        downloader_engine="go",
        download_workers=max(1, int(download_workers or 1)),
        download_timeout=max(1, int(download_timeout or 1)),
        download_retries=max(0, int(download_retries or 0)),
        catalog_engine=catalog_engine,
        playwright_engine=playwright_engine,
        spec_engine=spec_engine,
    )
